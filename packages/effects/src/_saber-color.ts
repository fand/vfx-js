export function saberColorRamp(rgb: readonly number[]): Float32Array {
    const [r, g, b] = rgb;
    const hi = Math.max(r, g, b),
        lo = Math.min(r, g, b);
    const chroma = hi - lo;
    let hue = 0;
    if (chroma > 0) {
        hue =
            hi === r
                ? ((g - b) / chroma + 6) % 6
                : hi === g
                  ? (b - r) / chroma + 2
                  : (r - g) / chroma + 4;
    }
    const index = hue * 6;
    const first = Math.floor(index) % 36,
        blend = index - Math.floor(index);
    const a = HUE_RAMPS[first],
        z = HUE_RAMPS[(first + 1) % 36];
    const result = new Float32Array(99);
    for (let i = 0; i < 33; i++) {
        const gray = (i / 32) ** 2;
        for (let c = 0; c < 3; c++) {
            const j = i * 3 + c;
            result[j] =
                gray * (1 - chroma) +
                (a[j] * (1 - blend) + z[j] * blend) * chroma;
        }
    }
    return result;
}
