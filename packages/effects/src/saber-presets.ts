function look(options: SaberOptions): SaberOptions {
    const result: SaberOptions = {
        ...BASE,
        ...options,
        coreDistortion: Object.freeze({
            ...DEFAULT_DISTORTION,
            ...options.coreDistortion,
        }),
        glowDistortion: Object.freeze({
            ...DEFAULT_DISTORTION,
            seed: 71,
            ...options.glowDistortion,
        }),
        glowLayers: (options.glowLayers ?? BASE.glowLayers).map((layer) =>
            Object.freeze({ ...layer }),
        ) as NonNullable<SaberOptions["glowLayers"]>,
    };
    Object.freeze(result.glowLayers);
    return Object.freeze(result);
}

