export function aeLightOptions(name: keyof typeof AE_PRESETS) {
    const p = AE_PRESETS[name];
    return {
        thickness: 2 * p.coreSize,
        coreSoftness: p.coreSoftness,
        coreBlendOnTop: p.coreBlendOnTop,
        color: p.color,
        gamma: p.gamma,
        brightness: p.brightness,
        saturation: p.saturation,
        glow: p.glowIntensity * (p.intensityMultiplier / 100) * 0.5,
        glowBias: p.bias,
        glowPreGamma: p.preGamma,
        glowSizeMultiplier: 1,
        haloIntensity: p.haloIntensity,
        haloSize: p.haloSize,
        glowLayers: p.layers.map((layer) => ({
            size: 2 * p.spread * p.sizeMultiplier * layer.size,
            intensity: layer.intensity,
        })) as NonNullable<SaberOptions["glowLayers"]>,
    };
}

/** Only directly isolated distortion mappings; noise shape remains approximate. */
export function aeTransportOptions(name: keyof typeof AE_PRESETS) {
    const p = AE_PRESETS[name];
    return {
        core: {
            ...p.coreNoise,
            motionBlur: p.coreNoise.motionBlur * 0.15,
            // Preserve the requested four-octave budget. Native fractional
            // complexity is retained in source data, not silently evaluated.
            noiseComplexity: 4,
            windSpeed: p.coreWindSpeed,
            windDirection: p.coreWindDirection,
        },
        glow: {
            ...p.glowNoise,
            motionBlur: p.glowNoise.motionBlur * 0.15,
            noiseComplexity: 4,
            amount: p.glowAmount,
            invert: p.glowInvert,
            composite: p.glowComposite,
            windSpeed: p.glowWindSpeed,
            windDirection: p.glowWindDirection,
        },
    };
}
