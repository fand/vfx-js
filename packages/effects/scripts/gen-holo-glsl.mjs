// Copies holospot's GLSL sources into src/_holo/glsl/*.ts (one string export per file), without their comments,
// trailing whitespace and blank lines (they ship in the bundle as strings, which a minifier does not touch); the code
// itself is verbatim.
// Usage: node scripts/gen-holo-glsl.mjs <path to holospot>
// The adaptations to vfx-js (atlas lookups, octahedral environment, the element as print layer) are applied at
// assembly time in src/_holo/shader.ts, so these files stay byte-identical to holospot's.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/gen-holo-glsl.mjs <holospot dir>");
const out = new URL("../src/_holo/glsl/", import.meta.url);
mkdirSync(out, { recursive: true });

const FILES = {
    common: "lib/common.glsl",
    spectral: "lib/spectral.glsl",
    ltc: "lib/ltc.glsl",
    lights: "lib/lights.glsl",
    relief: "lib/relief.glsl",
    coat: "lib/coat.glsl",
    wear: "lib/wear.glsl",
    grating: "lib/grating.glsl",
    ibl: "lib/ibl.glsl",
    glitter: "glitter.glsl",
    sparkle: "sparkle.glsl",
    holoPrism: "holo_prism.frag",
    holoShatter: "holo_shatter.frag",
    holoNebula: "holo_nebula.frag",
    holoSparkle: "holo_sparkle.frag",
    holoVortex: "holo_vortex.frag",
    holoEmboss: "holo_emboss.frag",
    paper: "paper.glsl",
    emboss: "emboss.glsl",
    env: "env.frag",
    output: "output.frag",
    glareDown: "glare_down.frag",
    glareUp: "glare_up.frag",
};

/** GLSL without comments (it has no string literals), trailing whitespace and blank lines; indentation stays. */
function stripComments(src) {
    let out = "";
    for (let i = 0; i < src.length; ) {
        if (src.startsWith("//", i)) {
            const e = src.indexOf("\n", i);
            i = e < 0 ? src.length : e;
        } else if (src.startsWith("/*", i)) {
            const e = src.indexOf("*/", i + 2);
            if (e < 0) throw new Error("unterminated block comment");
            // keep the line break of a multi-line comment, so the lines around it stay apart
            out += src.slice(i, e).includes("\n") ? "\n" : " ";
            i = e + 2;
        } else {
            out += src[i++];
        }
    }
    return out
        .split("\n")
        .map((l) => l.replace(/\s+$/, ""))
        .filter((l) => l !== "")
        .join("\n")
        .concat("\n");
}

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
for (const [name, file] of Object.entries(FILES)) {
    const src = stripComments(readFileSync(join(root, "engine/shaders", file), "utf8"));
    const body = src.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
    writeFileSync(
        new URL(`${kebab(name)}.ts`, out),
        `// holospot engine/shaders/${file} without comments (https://github.com/dmitrykurash/holospot), MIT © 2026 Dmitry Kurash.
// Generated by scripts/gen-holo-glsl.mjs. Do not edit.
export default \`${body}\`;
`,
    );
}
