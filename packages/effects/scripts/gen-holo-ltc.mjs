// Generates src/_holo/data/ltc.ts: three.js's LTC tables (RectAreaLightTexturesLib, MIT; data from Heitz et al.,
// https://github.com/selfshadow/ltc_code) rounded to half floats as holospot uploads them (LTC_HALF_1/2), packed as
// float24 bytes (src/_holo/spectral/float24.ts) in base64.
// Usage: node scripts/gen-holo-ltc.mjs <path to three's examples/jsm/lights/RectAreaLightTexturesLib.js>
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const lib = (await import(pathToFileURL(process.argv[2]).href)).RectAreaLightTexturesLib.init();
const { DataUtils } = await import(new URL("../../../build/three.module.js", pathToFileURL(process.argv[2])).href);

function float24(v, out, o) {
    const a = Math.abs(v);
    if (!(a >= 2 ** -62) || !Number.isFinite(v)) { out[o] = out[o + 1] = out[o + 2] = 0; return; }
    let e = Math.floor(Math.log2(a));
    let m = Math.round((a / 2 ** e - 1) * 65536);
    if (m >= 65536) { m = 0; e += 1; }
    out[o] = (v < 0 ? 128 : 0) + Math.min(Math.max(e + 63, 1), 127);
    out[o + 1] = m >> 8;
    out[o + 2] = m & 255;
}
const pack = (data) => {
    const out = new Uint8Array(data.length * 3);
    for (let i = 0; i < data.length; i++) float24(DataUtils.fromHalfFloat(DataUtils.toHalfFloat(data[i])), out, 3 * i);
    return Buffer.from(out).toString("base64");
};
const a = pack(lib.LTC_FLOAT_1.image.data), b = pack(lib.LTC_FLOAT_2.image.data);
writeFileSync(new URL("../src/_holo/data/ltc.ts", import.meta.url), `// Generated by scripts/gen-holo-ltc.mjs. Do not edit.
// LTC tables of three.js (RectAreaLightTexturesLib, MIT © three.js authors; fitted data from Heitz, Dupuy, Hill and
// Neubelt, "Real-Time Polygonal-Light Shading with Linearly Transformed Cosines", https://github.com/selfshadow/ltc_code),
// rounded to half floats as holospot uploads them. 64 × 64 RGBA each, row-major from v = 0, as float24 bytes in base64.
export const LTC_1 =
    "${a}";
export const LTC_2 =
    "${b}";
`);
