// Generates src/_holo/data/ltc.ts: three.js's LTC tables (RectAreaLightTexturesLib, MIT; data from Heitz et al.,
// https://github.com/selfshadow/ltc_code) rounded to half floats as holospot uploads them (LTC_HALF_1/2), packed for
// size (see pack); src/_holo/ltc.ts unpacks them into float24 bytes for the GPU decode.
// Usage: node scripts/gen-holo-ltc.mjs <path to three's examples/jsm/lights/RectAreaLightTexturesLib.js>
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const lib = (await import(pathToFileURL(process.argv[2]).href)).RectAreaLightTexturesLib.init();
const { DataUtils } = await import(new URL("../../../build/three.module.js", pathToFileURL(process.argv[2])).href);

// Packed for size (gzip): each half float minus the one in the row above (same column and channel, mod 2^16), then
// the high bytes of all values followed by the low bytes, in base64. src/_holo/ltc.ts undoes it.
const ROW = 4 * 64;
const pack = (data) => {
    const h = Uint16Array.from(data, (v) => DataUtils.toHalfFloat(v));
    const out = Buffer.alloc(h.length * 2);
    for (let i = 0; i < h.length; i++) {
        const d = (h[i] - (i >= ROW ? h[i - ROW] : 0)) & 0xffff;
        out[i] = d >> 8;
        out[h.length + i] = d & 255;
    }
    return out.toString("base64");
};
const a = pack(lib.LTC_FLOAT_1.image.data), b = pack(lib.LTC_FLOAT_2.image.data);
writeFileSync(new URL("../src/_holo/data/ltc.ts", import.meta.url), `// Generated by scripts/gen-holo-ltc.mjs. Do not edit.
// LTC tables of three.js (RectAreaLightTexturesLib, MIT © three.js authors; fitted data from Heitz, Dupuy, Hill and
// Neubelt, "Real-Time Polygonal-Light Shading with Linearly Transformed Cosines", https://github.com/selfshadow/ltc_code),
// rounded to half floats as holospot uploads them. 64 × 64 RGBA each, row-major from v = 0: each half float minus the
// one in the row above, high bytes then low bytes, in base64 (scripts/gen-holo-ltc.mjs).
export const LTC_1 =
    "${a}";
export const LTC_2 =
    "${b}";
`);
