// Generates src/_bubble-kernel-source.ts: the source text of BubbleEffect's
// worker kernel (bubbleKernel in src/_bubble-fill.ts) as a string literal,
// with its types stripped. As for HoloEffect's kernels (see
// gen-holo-kernels.mjs), the worker is built from this string rather than
// from Function.prototype.toString() at run time, which a consumer's
// bundler may have rewritten.
// Usage: node scripts/gen-bubble-kernel.mjs (src/_bubble-kernel.test.ts
// checks the file is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

/** Function `name` of `src/<file>` as plain JavaScript: `function name() { ... }`. */
export function functionSource(file, name) {
    const path = fileURLToPath(new URL(`../src/${file}`, import.meta.url));
    const sf = ts.createSourceFile(
        path,
        readFileSync(path, "utf8"),
        ts.ScriptTarget.Latest,
        true,
    );
    const fn = sf.statements.find(
        (s) => ts.isFunctionDeclaration(s) && s.name?.text === name,
    );
    if (!fn) {
        throw new Error(`${file}: no function ${name}`);
    }
    const text = fn.getText(sf).replace(/^export\s+/, "");
    return ts
        .transpileModule(text, {
            compilerOptions: {
                target: ts.ScriptTarget.ES2022,
                module: ts.ModuleKind.ESNext,
                removeComments: true,
            },
        })
        .outputText.replace(/^"use strict";\s*/, "")
        .trim();
}

/** bubbleKernel as plain JavaScript: `function bubbleKernel() { ... }`. */
export function bubbleKernelSource() {
    return functionSource("_bubble-fill.ts", "bubbleKernel");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(
        new URL("../src/_bubble-kernel-source.ts", import.meta.url),
        `// Generated by scripts/gen-bubble-kernel.mjs from _bubble-fill.ts. Do not edit.
// The worker kernel as source text: a bundler leaves a string literal alone.

/** bubbleKernel (_bubble-fill.ts) as plain JavaScript. */
export const BUBBLE_KERNEL_SOURCE = ${JSON.stringify(bubbleKernelSource())};
`,
    );
}
