// Generates src/_shape-kernel-source.ts: the source text of the
// silhouette's worker kernel (shapeKernel in src/_silhouette.ts), as for
// BubbleEffect's kernel (see gen-bubble-kernel.mjs).
// Usage: node scripts/gen-shape-kernel.mjs (src/_shape-kernel.test.ts
// checks the file is up to date)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { functionSource } from "./gen-bubble-kernel.mjs";

/** shapeKernel as plain JavaScript: `function shapeKernel() { ... }`. */
export function shapeKernelSource() {
    return functionSource("_silhouette.ts", "shapeKernel");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(
        new URL("../src/_shape-kernel-source.ts", import.meta.url),
        `// Generated by scripts/gen-shape-kernel.mjs from _silhouette.ts. Do not edit.
// The worker kernel as source text: a bundler leaves a string literal alone.

/** shapeKernel (_silhouette.ts) as plain JavaScript. */
export const SHAPE_KERNEL_SOURCE = ${JSON.stringify(shapeKernelSource())};
`,
    );
}
