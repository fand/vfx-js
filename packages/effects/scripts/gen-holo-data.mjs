// Generates src/_holo/data/*.ts from a holospot checkout's src/data/*.json.
// Usage: node scripts/gen-holo-data.mjs <path to holospot>
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) throw new Error("usage: node scripts/gen-holo-data.mjs <holospot dir>");
const read = (f) => JSON.parse(readFileSync(join(root, "src/data", f), "utf8"));
const out = new URL("../src/_holo/data/", import.meta.url);
mkdirSync(out, { recursive: true });

const MATERIALS = ["prism", "shatter", "nebula", "sparkle", "vortex", "emboss"];
// Foil Emboss ids this port does not support: the hologram sticker (needs the volume-hologram assets), the
// multi-element document, the editor, the printed picture (the element is the print) and the card's thickness.
const EMBOSS_UNSUPPORTED = /^emboss\.(holo\..*|element|shape|aspect|cornerRadius|edit|doc|filmUm|filmWall|thickness)$/;
const SCENE_IDS = [
    /^studio\./,
    /^display\.(ev|tone|glare|glareRadius)$/,
    /^grain\./,
    /^card\.(bow|bowAxis|emboss|embossPitch|embossHeight|embossLayer|wear)$/,
    /^motion\.(pointer|tiltRange|pose|wobble|wobbleAmp)$/,
    /^scene\.(background|bgColor)$/,
    /^dof\.lens$/,
];
const supported = (id) =>
    !EMBOSS_UNSUPPORTED.test(id) &&
    (SCENE_IDS.some((r) => r.test(id)) || MATERIALS.includes(id.split(".")[0]));

const params = read("params.json");
// The port's own defaults where it departs from holospot's: holo.spot's looks use 0.07 grain, not the 0.18 default.
// The port ships none of holo.spot's logo marks: no logo unless one is given (an image or a URL).
const PORT_DEFAULTS = { "grain.amount": 0.07, "emboss.logo": "" };
// Options the port adds: "none" ignores the pointer (an element effect may not want it).
const PORT_OPTIONS = { "motion.pointer": ["tilt", "light", "flash", "none"] };
// The emboss logo's placement is in CSS px of the element (the port's; holo.spot's are mm on its 63 × 88 mm card).
// No default: centred, 36/63 of the element's width (holo.spot's proportion).
const PX_PLACEMENT = {
    "emboss.x": { id: "emboss.x", kind: "slider", default: null, step: 1 },
    "emboss.y": { id: "emboss.y", kind: "slider", default: null, step: 1 },
    "emboss.width": { id: "emboss.width", kind: "slider", default: null, min: 1, step: 1 },
};
const keep = (p) => {
    if (PX_PLACEMENT[p.id]) return PX_PLACEMENT[p.id];
    const o = { id: p.id, kind: p.kind, default: PORT_DEFAULTS[p.id] ?? p.default };
    if (p.min !== undefined) o.min = p.min;
    if (p.max !== undefined) o.max = p.max;
    if (p.step !== undefined) o.step = p.step;
    const options = p.id === "emboss.logo" ? undefined : (PORT_OPTIONS[p.id] ?? p.options);
    if (options) o.options = options;
    return o;
};
// holo.spot ids the kit ignores too (its site's objects, orbit, pointer controller), and the Volume Hologram material:
// accepted without a warning.
const SITE_ONLY = /^(scene\.|object\.|motion\.|display\.quality$|studio\.flash\.|volume\.)/;
const specs = [
    ...params.scene.filter((p) => supported(p.id)),
    ...MATERIALS.flatMap((m) => params.materials[m]),
]
    .filter((p) => supported(p.id))
    .map(keep);
// The port's own: where the logo image's coverage is cut into foil / no foil (holospot cuts at ½).
specs.splice(specs.findIndex((p) => p.id === "emboss.logo") + 1, 0, {
    id: "emboss.threshold",
    kind: "slider",
    default: 0.5,
    min: 0.01,
    max: 0.99,
    step: 0.01,
});

const header = `// Generated by scripts/gen-holo-data.mjs from holospot src/data (https://github.com/dmitrykurash/holospot),
// MIT © 2026 Dmitry Kurash. Do not edit.
`;
const ts = (v) => JSON.stringify(v, null, 4);

writeFileSync(
    new URL("params.ts", out),
    `${header}import type { ParamSpec } from "../settings-types.js";

/** Every holo.spot setting id this effect understands. */
export type HoloSettingId =
${specs.map((p) => `    | ${JSON.stringify(p.id)}`).join("\n")};

export const PARAM_SPECS: readonly ParamSpec[] = ${ts(specs)};
`,
);

// holo.spot ids this port does not render, with holospot's defaults: given a different value, the effect warns.
const allHolospot = [...params.scene, ...Object.values(params.materials).flat()];
const notPorted = Object.fromEntries(
    allHolospot
        .filter((p) => !supported(p.id) && !SITE_ONLY.test(p.id) && p.id !== "object.structureScale")
        .map((p) => [p.id, p.default]),
);
const ignored = allHolospot.filter((p) => !supported(p.id) && !(p.id in notPorted)).map((p) => p.id);
writeFileSync(
    new URL("not-ported.ts", out),
    `${header}import type { ParamValue } from "../types.js";

/** holo.spot settings the port does not render, with holospot's defaults (a different value warns). */
export const NOT_PORTED: Readonly<Record<string, ParamValue>> = ${ts(notPorted)};

/** holo.spot settings the port accepts and ignores without a warning, as holospot's kit does. */
export const IGNORED_IDS: ReadonlySet<string> = new Set(${ts(ignored)});
`,
);

const looks = read("looks.json");
const lookOut = {};
// holo.spot ships Foil Emboss on its paper card (the look `image`), not on its card or 3D object: the port's `card`
// look of emboss is that paper card, without the site's own logo artwork.
const lookOf = (name, m) =>
    m === "emboss" ? (name === "card" ? looks.image.surfaces.emboss : null) : looks[name].surfaces[m];
for (const name of ["card", "object"]) {
    lookOut[name] = {};
    for (const m of MATERIALS) {
        const s = lookOf(name, m);
        if (!s) continue;
        const values = Object.fromEntries(
            Object.entries(s.values).filter(
                ([id]) =>
                    supported(id) &&
                    // the site's own artwork, and its placement in mm on a 63 × 88 mm card (the port's is in px)
                    !["emboss.logo", "emboss.x", "emboss.y", "emboss.width"].includes(id),
            ),
        );
        lookOut[name][m] = { values, pose: { rx: s.pose.rx, ry: s.pose.ry } };
    }
}
writeFileSync(
    new URL("looks.ts", out),
    `${header}import type { LookData } from "../settings-types.js";

export const LOOKS: LookData = ${ts(lookOut)};
`,
);

writeFileSync(
    new URL("material-presets.ts", out),
    `${header}import type { ParamValue } from "../types.js";

/** Material selects that write a preset of other values (holospot params.json \`presets\`): id → option → values. */
export const MATERIAL_PRESETS: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, ParamValue>>>>>> = ${ts(params.presets.emboss)};
`,
);

// The "Starting points" of holospot's material docs (docs/materials/<material>.md): a bold name, a sentence, a JSON map.
// A starting point that needs an unported feature (the emboss hologram sticker) is skipped.
const camel = (name) =>
    name
        .toLowerCase()
        .replace(/[^a-z0-9]+(.)/g, (_, c) => c.toUpperCase())
        .replace(/[^a-zA-Z0-9]/g, "");
const startingPoints = {};
for (const m of MATERIALS) {
    const md = readFileSync(join(root, "docs/materials", `${m}.md`), "utf8");
    const sec = md.split("## Starting points")[1]?.split("\n## ")[0] ?? "";
    const out = {};
    for (const [, name, json] of sec.matchAll(/\*\*([^*]+?)\.\*\*[^\n]*\n+```json\n([\s\S]*?)```/g)) {
        const values = JSON.parse(json);
        if (Object.keys(values).some((id) => !supported(id))) continue;
        delete values["emboss.logo"]; // holo.spot's own marks are not shipped
        for (const id of Object.keys(PX_PLACEMENT)) delete values[id]; // mm on holo.spot's card, not px
        out[camel(name)] = values;
    }
    startingPoints[m] = out;
}
writeFileSync(
    new URL("starting-points.ts", out),
    `${header}import type { ParamValue } from "../types.js";

/** holospot's material "Starting points" (docs/materials/<material>.md), by material and camel-cased name. */
/** Names of holospot's material starting points, by material (\`HoloEffect.startingPoints\`). */
export type HoloStartingPointNames = {
${Object.entries(startingPoints)
    .map(([m, ps]) => `    ${m}: ${Object.keys(ps).map((n) => JSON.stringify(n)).join(" | ")};`)
    .join("\n")}
};

export const STARTING_POINTS = ${ts(startingPoints)} as const satisfies Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, ParamValue>>>>>>;
`,
);

const presets = read("studio-presets.json");
writeFileSync(
    new URL("studio-presets.ts", out),
    `${header}import type { ParamValue } from "../types.js";

export const STUDIO_PRESETS: Readonly<Record<string, Readonly<Record<string, ParamValue>>>> = ${ts(presets)};
`,
);
