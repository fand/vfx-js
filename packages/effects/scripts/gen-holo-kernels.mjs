// Generates src/_holo/data/kernels.ts: the source text of HoloEffect's worker kernels (logoKernel in
// src/_holo/scene/logo.ts, paperKernel in src/_holo/scene/paper-maps.ts) as string literals, with their types stripped.
// The workers are built from these strings, not from Function.prototype.toString() at run time: a consumer's bundler
// or transpiler may rewrite a function (inject helpers such as esbuild's __name or Babel's), and those helpers do not
// exist inside the worker. It leaves the contents of a string literal alone.
// Usage: node scripts/gen-holo-kernels.mjs (src/_holo/kernels.test.ts checks the file is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const src = new URL("../src/_holo/", import.meta.url);

/** The kernel factory `name` of `file` (relative to src/_holo) as plain JavaScript: `function name() { ... }`. */
function kernelSource(file, name) {
    const path = fileURLToPath(new URL(file, src));
    const sf = ts.createSourceFile(path, readFileSync(path, "utf8"), ts.ScriptTarget.Latest, true);
    const fn = sf.statements.find((s) => ts.isFunctionDeclaration(s) && s.name?.text === name);
    if (!fn) throw new Error(`${file}: no function ${name}`);
    const text = fn.getText(sf).replace(/^export\s+/, "");
    return ts
        .transpileModule(text, {
            compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: true },
        })
        .outputText.replace(/^"use strict";\s*/, "") // the worker adds its own
        .trim();
}

/** The kernels' sources, as written to src/_holo/data/kernels.ts. */
export function kernelSources() {
    return {
        logo: kernelSource("scene/logo.ts", "logoKernel"),
        paper: kernelSource("scene/paper-maps.ts", "paperKernel"),
    };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const k = kernelSources();
    writeFileSync(
        new URL("data/kernels.ts", src),
        `// Generated by scripts/gen-holo-kernels.mjs from scene/logo.ts and scene/paper-maps.ts. Do not edit.
// The worker kernels as source text: a bundler leaves a string literal alone (see the script).

/** logoKernel (scene/logo.ts) as plain JavaScript. */
export const LOGO_KERNEL_SOURCE = ${JSON.stringify(k.logo)};

/** paperKernel (scene/paper-maps.ts) as plain JavaScript. */
export const PAPER_KERNEL_SOURCE = ${JSON.stringify(k.paper)};
`,
    );
}
